import { invoke } from '@tauri-apps/api/core'
import { listen, type UnlistenFn } from '@tauri-apps/api/event'

/** Engine running a module. */
export type EngineKind = 'component' | 'extism'

export interface ParamInfo {
  /** Argument key (camelCase). */
  name: string
  /** Type in WIT syntax. */
  type: string
}

export interface CommandInfo {
  /** Name to pass to {@link invokeModule}. */
  name: string
  /** Parameters (WIT modules only). */
  params: ParamInfo[]
  /** Result type in WIT syntax (WIT modules only). */
  result: string | null
}

/** What a module is allowed to do. See "Capabilities" in the README. */
export interface Capabilities {
  /** Host commands it may invoke. `*` wildcards; `!` entries deny. */
  hostCommands: string[]
  events: {
    /** Events it may emit. `*` wildcards; `!` entries deny. */
    emit: string[]
    /** Events delivered to it. */
    listen: string[]
  }
  /** Keys of its state store it may use. `*` wildcards; `!` entries deny. */
  state: string[]
  wasi: {
    stdio: boolean
    env: Record<string, string>
    preopens: Array<{ host: string; guest: string; readOnly: boolean }>
    network: boolean
  }
  /** Hosts it may reach over HTTP (Extism modules). */
  allowedHosts: string[]
  memoryLimitMb: number | null
  timeoutMs: number | null
  maxRestarts: number | null
}

export interface ModuleInfo {
  name: string
  engine: EngineKind
  path: string | null
  /** Loaded from the external plugins directory. */
  external: boolean
  /** Invocable without an explicit `allow-invoke` scope entry. */
  exposed: boolean
  /** Reloaded automatically when its file changes. */
  watched: boolean
  /** Incremented on every reload. */
  generation: number
  /** SHA-256 of the module's bytes, in lowercase hex. */
  sha256: string
  /**
   * Every interface the module imports, as it names them (WIT modules only):
   * all it can reach outside its own memory.
   */
  requires: string[]
  /** Calls that trapped since the module was last (re)loaded. */
  traps: number
  /**
   * The module trapped more often than its `maxRestarts` capability allows:
   * every call fails until it is reloaded.
   */
  stopped: boolean
  commands: CommandInfo[]
  /**
   * Host commands the module imports as typed WIT functions, named as
   * registered. Checked when the module loads.
   */
  imports: CommandInfo[]
  capabilities: Capabilities
  /**
   * Likely configuration mistakes found when the module was (re)loaded, e.g.
   * a `hostCommands` entry matching no registered host command.
   */
  warnings: string[]
}

/**
 * Why a module is not running: switched off, refused (by the app's load
 * gate, the external plugins' allow and deny lists or a pinned hash) or
 * failed to load.
 */
export type InactiveReason = 'disabled' | 'denied' | 'failed'

/** A module the app knows but isn't running. */
export interface InactiveModule {
  name: string
  path: string | null
  /** Found in the external plugins directory. */
  external: boolean
  /** SHA-256 of its bytes in lowercase hex, when they were read. */
  sha256: string | null
  reason: InactiveReason
  /** The reason in words: the load gate's answer, the load error, … */
  message: string
  /** What it would be allowed to do if it ran. */
  capabilities: Capabilities
}

export interface ModuleError {
  module: string
  error: string
}

export interface ModuleTrap {
  module: string
  error: string
  /** Traps since the module was last (re)loaded, this one included. */
  traps: number
  /** Whether this trap stopped the module until it is reloaded. */
  stopped: boolean
}

export const EVENT_MODULE_LOADED = 'wasm-backend://module-loaded'
export const EVENT_MODULE_RELOADED = 'wasm-backend://module-reloaded'
export const EVENT_MODULE_UNLOADED = 'wasm-backend://module-unloaded'
export const EVENT_MODULE_ERROR = 'wasm-backend://module-error'
export const EVENT_MODULE_TRAPPED = 'wasm-backend://module-trapped'

/**
 * Invoke a command of a WASM backend module, the same way `invoke` calls a
 * Rust command.
 *
 * For WIT modules `args` is an object keyed by parameter name
 * (`greet: func(name: string)` → `{ name }`). For Extism modules `args` is
 * passed to the function as its JSON input.
 *
 * Rejects with the module's error value when the command returns the `err`
 * case of a WIT `result` (or an Extism error), like a Rust command returning
 * `Err`.
 */
export async function invokeModule<T = unknown>(
  module: string,
  command: string,
  args?: unknown
): Promise<T> {
  return await invoke<T>('plugin:wasm-backend|invoke', {
    module,
    command,
    args: args ?? null
  })
}

/**
 * An untyped client for a module: `module('greeter').greet({ name })`.
 *
 * For typed clients, use the bindings generated by the plugin (see
 * `typescriptOutDir` in the README).
 */
export function module<T extends object = Record<string, (args?: unknown) => Promise<unknown>>>(
  name: string
): T {
  return new Proxy({} as T, {
    get(_target, command) {
      if (typeof command !== 'string' || command === 'then') return undefined
      return (args?: unknown) => invokeModule(name, command, args)
    }
  })
}

/** List the loaded modules and their commands. */
export async function listModules(): Promise<ModuleInfo[]> {
  return await invoke<ModuleInfo[]>('plugin:wasm-backend|list_modules')
}

/**
 * List the modules that are known but not running, and why. Together with
 * {@link listModules} this is every module the app has. Requires the
 * `wasm-backend:allow-list-inactive-modules` permission.
 */
export async function listInactiveModules(): Promise<InactiveModule[]> {
  return await invoke<InactiveModule[]>('plugin:wasm-backend|list_inactive_modules')
}

/**
 * Load a module {@link listInactiveModules} lists: one that was switched
 * off, or one that was refused or failed and should be tried again. The app
 * still decides whether it may load. Requires the
 * `wasm-backend:allow-enable-module` permission.
 */
export async function enableModule(name: string): Promise<ModuleInfo> {
  return await invoke<ModuleInfo>('plugin:wasm-backend|enable_module', { module: name })
}

/**
 * Switch a module off until it is enabled again (or the app restarts); its
 * state is kept. Requires the `wasm-backend:allow-disable-module`
 * permission.
 */
export async function disableModule(name: string): Promise<void> {
  await invoke('plugin:wasm-backend|disable_module', { module: name })
}

/**
 * Reload a module from its file (resetting its state). Requires the
 * `wasm-backend:allow-reload-module` permission.
 */
export async function reloadModule(name: string): Promise<ModuleInfo> {
  return await invoke<ModuleInfo>('plugin:wasm-backend|reload_module', {
    module: name
  })
}

/**
 * TypeScript bindings for a module, generated from its exported types.
 * Requires the `wasm-backend:allow-typescript` permission.
 */
export async function moduleTypescript(name: string): Promise<string> {
  return await invoke<string>('plugin:wasm-backend|typescript', { module: name })
}

/** Called when a module is loaded. */
export async function onModuleLoaded(cb: (info: ModuleInfo) => void): Promise<UnlistenFn> {
  return await listen<ModuleInfo>(EVENT_MODULE_LOADED, (e) => cb(e.payload))
}

/** Called when a module is hot reloaded. */
export async function onModuleReloaded(cb: (info: ModuleInfo) => void): Promise<UnlistenFn> {
  return await listen<ModuleInfo>(EVENT_MODULE_RELOADED, (e) => cb(e.payload))
}

/** Called when a module is unloaded. */
export async function onModuleUnloaded(cb: (name: string) => void): Promise<UnlistenFn> {
  return await listen<string>(EVENT_MODULE_UNLOADED, (e) => cb(e.payload))
}

/** Called when a module fails to load or reload. */
export async function onModuleError(cb: (error: ModuleError) => void): Promise<UnlistenFn> {
  return await listen<ModuleError>(EVENT_MODULE_ERROR, (e) => cb(e.payload))
}

/**
 * Called when a call into a module traps (a panic, a timeout, running out of
 * memory). `stopped` says whether the module now needs a reload.
 */
export async function onModuleTrapped(cb: (trap: ModuleTrap) => void): Promise<UnlistenFn> {
  return await listen<ModuleTrap>(EVENT_MODULE_TRAPPED, (e) => cb(e.payload))
}
