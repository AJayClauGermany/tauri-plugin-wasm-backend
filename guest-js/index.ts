import { invoke } from '@tauri-apps/api/core'
import { listen, type UnlistenFn } from '@tauri-apps/api/event'

/** Engine running a module. */
export type EngineKind = 'component' | 'extism'

export interface ParamInfo {
  /** Argument key (camelCase). */
  name: string
  /** Type in WIT syntax. */
  type: string
}

export interface CommandInfo {
  /** Name to pass to {@link invokeModule}. */
  name: string
  /** Parameters (WIT modules only). */
  params: ParamInfo[]
  /** Result type in WIT syntax (WIT modules only). */
  result: string | null
}

export interface ModuleInfo {
  name: string
  engine: EngineKind
  path: string | null
  /** Loaded from the external plugins directory. */
  external: boolean
  /** Invocable without an explicit `allow-invoke` scope entry. */
  exposed: boolean
  /** Reloaded automatically when its file changes. */
  watched: boolean
  /** Incremented on every reload. */
  generation: number
  commands: CommandInfo[]
  capabilities: Record<string, unknown>
}

export interface ModuleError {
  module: string
  error: string
}

export const EVENT_MODULE_LOADED = 'wasm-backend://module-loaded'
export const EVENT_MODULE_RELOADED = 'wasm-backend://module-reloaded'
export const EVENT_MODULE_UNLOADED = 'wasm-backend://module-unloaded'
export const EVENT_MODULE_ERROR = 'wasm-backend://module-error'

/**
 * Invoke a command of a WASM backend module, the same way `invoke` calls a
 * Rust command.
 *
 * For WIT modules `args` is an object keyed by parameter name
 * (`greet: func(name: string)` → `{ name }`). For Extism modules `args` is
 * passed to the function as its JSON input.
 *
 * Rejects with the module's error value when the command returns the `err`
 * case of a WIT `result` (or an Extism error), like a Rust command returning
 * `Err`.
 */
export async function invokeModule<T = unknown>(
  module: string,
  command: string,
  args?: unknown
): Promise<T> {
  return await invoke<T>('plugin:wasm-backend|invoke', {
    module,
    command,
    args: args ?? null
  })
}

/**
 * An untyped client for a module: `module('greeter').greet({ name })`.
 *
 * For typed clients, use the bindings generated by the plugin (see
 * `typescriptOutDir` in the README).
 */
export function module<T extends object = Record<string, (args?: unknown) => Promise<unknown>>>(
  name: string
): T {
  return new Proxy({} as T, {
    get(_target, command) {
      if (typeof command !== 'string' || command === 'then') return undefined
      return (args?: unknown) => invokeModule(name, command, args)
    }
  })
}

/** List the loaded modules and their commands. */
export async function listModules(): Promise<ModuleInfo[]> {
  return await invoke<ModuleInfo[]>('plugin:wasm-backend|list_modules')
}

/**
 * Reload a module from its file (resetting its state). Requires the
 * `wasm-backend:allow-reload-module` permission.
 */
export async function reloadModule(name: string): Promise<ModuleInfo> {
  return await invoke<ModuleInfo>('plugin:wasm-backend|reload_module', {
    module: name
  })
}

/**
 * TypeScript bindings for a module, generated from its exported types.
 * Requires the `wasm-backend:allow-typescript` permission.
 */
export async function moduleTypescript(name: string): Promise<string> {
  return await invoke<string>('plugin:wasm-backend|typescript', { module: name })
}

/** Called when a module is loaded. */
export async function onModuleLoaded(cb: (info: ModuleInfo) => void): Promise<UnlistenFn> {
  return await listen<ModuleInfo>(EVENT_MODULE_LOADED, (e) => cb(e.payload))
}

/** Called when a module is hot reloaded. */
export async function onModuleReloaded(cb: (info: ModuleInfo) => void): Promise<UnlistenFn> {
  return await listen<ModuleInfo>(EVENT_MODULE_RELOADED, (e) => cb(e.payload))
}

/** Called when a module is unloaded. */
export async function onModuleUnloaded(cb: (name: string) => void): Promise<UnlistenFn> {
  return await listen<string>(EVENT_MODULE_UNLOADED, (e) => cb(e.payload))
}

/** Called when a module fails to load or reload. */
export async function onModuleError(cb: (error: ModuleError) => void): Promise<UnlistenFn> {
  return await listen<ModuleError>(EVENT_MODULE_ERROR, (e) => cb(e.payload))
}
